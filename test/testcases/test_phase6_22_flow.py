"""Saved controlled labels and metadata from actual Chrome through the stack worker."""
import json
from pathlib import Path

import pytest

from test.helpers.accounts import AccountRegistry
from test.helpers.chrome_cdp import ChromeSession
from test.helpers.fake_provider import running_stack_fake_provider
from test.helpers.ingest import upload_text
from test.helpers.wait import wait_until
from test.testcases.conftest import BASE_URL
from test.testcases.test_dataset_flow import CHAT_ID, create, workspace
from test.testcases.test_provider_flow import api, ok
from test.testcases.test_spa_browser import _set_viewport, _type_into, _wait_testid
from test.testcases.test_spa_ingestion_browser import Scene, _press

pytestmark = pytest.mark.e2e


def _select(browser: ChromeSession, test_id: str, value: str) -> None:
    browser.wait_for("!!document.querySelector('[data-testid=" + json.dumps(test_id) + "] option[value=" + json.dumps(value) + "]')", f"{test_id} model option")
    browser.evaluate("(() => { const field=document.querySelector('[data-testid=" + json.dumps(test_id) + "]'); field.value=" + json.dumps(value) + "; field.dispatchEvent(new Event('change',{bubbles:true})); })()")


def test_browser_saves_controls_and_sees_generated_data_with_source_intact(ingress, repo_root):
    accounts = AccountRegistry(BASE_URL)
    try:
        with running_stack_fake_provider() as fake:
            owner = workspace(ingress, accounts, fake, "controlled")
            dataset = ok(create(ingress, owner))["id"]
            scene = Scene(ingress, owner, fake, dataset)
            source = (repo_root / "test/fixtures/phase6/controlled-enrichment-original.txt").read_text().strip()
            with ChromeSession() as browser:
                _set_viewport(browser)
                scene.files(browser)
                _press(browser, "dataset-tags-open")
                _wait_testid(browser, "tag-generation-config")
                _press(browser, "tag-auto-generate")
                _type_into(browser, "allowed-tags", "lighthouse\ncalibration")
                _select(browser, "tag-model", CHAT_ID)
                _press(browser, "tag-config-save")
                wait_until(lambda: ok(api(ingress, "GET", f"/api/v1/datasets/{dataset}", owner.token))["parser_config"].get("auto_tags") is True, timeout=30)
                _press(browser, "dataset-metadata-open")
                _wait_testid(browser, "metadata-generation-config")
                _press(browser, "metadata-auto-generate")
                _select(browser, "metadata-model", CHAT_ID)
                _press(browser, "metadata-schema-add")
                _type_into(browser, "metadata-schema-name", "tower_height_metres")
                _select(browser, "metadata-schema-type", "number")
                _press(browser, "metadata-schema-required")
                _press(browser, "metadata-config-save")
                wait_until(lambda: ok(api(ingress, "GET", f"/api/v1/datasets/{dataset}", owner.token))["parser_config"].get("auto_metadata") is True, timeout=30)
                doc = upload_text(ingress, owner, dataset, source.encode(), "controlled-original.txt")
                fake.chat_responses[:] = [
                    json.dumps({"items": [{"index": 0, "tags": ["lighthouse", "calibration"]}]}),
                    json.dumps({"metadata": {"tower_height_metres": 52}}),
                ]
                before = len(fake.chat_requests())
                scene.parse(doc["id"])
                assert len(fake.chat_requests()) == before + 2
                detail = ok(api(ingress, "GET", f"/api/v1/datasets/{dataset}/documents/{doc['id']}", owner.token))
                assert detail["metadata"] == {"tower_height_metres": 52}
                assert detail["metadata_provenance"] == {"tower_height_metres": "generated"}
                tags = ok(api(ingress, "GET", f"/api/v1/datasets/{dataset}/tags", owner.token))
                assert {(item["tag"], item.get("origin")) for item in tags["items"]} == {("lighthouse", "generated"), ("calibration", "generated")}
                chunks = ok(api(ingress, "GET", f"/api/v1/datasets/{dataset}/documents/{doc['id']}/chunks", owner.token))
                assert chunks["total"] == 1 and chunks["items"][0]["text"] == source
                scene.files(browser)
                _press(browser, "dataset-tags-open")
                browser.wait_for("document.querySelector('[data-testid=dataset-tags-section]')?.textContent.includes('lighthouse')", "generated tag visible")
                _press(browser, "dataset-metadata-open")
                _press(browser, "document-select")
                browser.wait_for("document.querySelector('[data-testid=metadata-field-value]')?.textContent.includes('tower_height_metres: 52')", "generated metadata value visible")
                assert "Generated by model" in browser.evaluate("document.querySelector('[data-testid=metadata-field-value]').textContent")
                output = Path("output/playwright/phase6-review")
                output.mkdir(parents=True, exist_ok=True)
                browser.evaluate("document.querySelector('[data-testid=metadata-selected-values]').scrollIntoView({block:'center'})")
                browser.screenshot(str(output / "controlled-metadata.png"))
                browser.evaluate("document.querySelector('[data-testid=generated-tag-label]').scrollIntoView({block:'center'})")
                browser.screenshot(str(output / "controlled-tags.png"))
    finally:
        accounts.cleanup()
